from pathlib import Path
from playwright.sync_api import sync_playwright

SHOTS = Path(r"C:\chrono-fracture\tests\shots")
errors = []
with sync_playwright() as p:
    browser = p.chromium.launch(channel="msedge", headless=True)
    page = browser.new_context(viewport={"width": 1280, "height": 800}).new_page()
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.goto("http://127.0.0.1:8123/index.html", wait_until="load")
    page.wait_for_timeout(2500)
    page.click('[data-action="goto-settings"]')
    page.wait_for_timeout(500)
    print("OPEN", page.evaluate("() => [CF.app.state.screen, document.querySelector('.menu-title').textContent]"))
    page.click('[data-lang="en"]')
    page.wait_for_timeout(500)
    print("EN", page.evaluate("() => [CF.i18n.getLang(), document.querySelector('.menu-title').textContent, CF.store.settings.lang]"))
    page.screenshot(path=str(SHOTS / "s01-settings-en.png"))
    page.click('[data-action="settings-done"]')
    page.wait_for_timeout(700)
    print("DONE", page.evaluate("() => [CF.app.state.screen, CF.store.settings.lang, document.querySelector('#toastLayer').innerText]"))
    page.screenshot(path=str(SHOTS / "s02-settings-done.png"))
    page.click('[data-action="goto-settings"]')
    page.wait_for_timeout(400)
    page.click('[data-lang="es"]')
    page.wait_for_timeout(400)
    page.click('[data-action="settings-back"]')
    page.wait_for_timeout(500)
    print("BACK", page.evaluate("() => [CF.app.state.screen, CF.i18n.getLang()]"))
    print("ERRORS", errors)
    browser.close()
