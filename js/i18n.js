  var current = 'es';

  function normalize(lang) {
    lang = String(lang || '').toLowerCase();
    if (lang.indexOf('pt') === 0) return 'pt';
    if (lang.indexOf('en') === 0) return 'en';
    return 'es';
  }

  function t(key, vars) {
    var table = DICT[current] || DICT.es;
    var value = table[key];
    if (value == null) value = DICT.es[key];
    if (value == null) value = key;
    if (vars) {
      value = value.replace(/\{(\w+)\}/g, function (m, name) {
        return vars[name] != null ? vars[name] : m;
      });
    }
    return value;
  }

  function setLang(lang) {
    current = normalize(lang);
  }

  function getLang() { return current; }

  function langLabel(lang) { return t('lang.' + normalize(lang)); }

  function applyDom(root) {
    var scope = root || document;
    var nodes = scope.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n');
      if (key) nodes[i].textContent = t(key);
    }
    var ph = scope.querySelectorAll('[data-i18n-placeholder]');
    for (var j = 0; j < ph.length; j++) {
      ph[j].setAttribute('placeholder', t(ph[j].getAttribute('data-i18n-placeholder')));
    }
    var ar = scope.querySelectorAll('[data-i18n-aria]');
    for (var k = 0; k < ar.length; k++) {
      ar[k].setAttribute('aria-label', t(ar[k].getAttribute('data-i18n-aria')));
    }
  }

  window.CF = window.CF || {};
  window.CF.i18n = {
    t: t,
    setLang: setLang,
    getLang: getLang,
    normalize: normalize,
    langLabel: langLabel,
    applyDom: applyDom,
    dict: DICT
  };
